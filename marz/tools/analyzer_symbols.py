#!/usr/bin/env python3
"""Turns the analyzer's name@address entries into config/symbols/sdk.txt lines.

A name matched at several addresses is reported and left out unless it is in KEEP_MULTI (the
wrappers Sony really does ship twice): the Gitaroo port found that database matches at many
addresses are small look-alike functions, not the library function.

Usage: analyzer_symbols.py <analyzer.toml> <sdk.txt>
"""
import collections
import re
import sys

src, dst = sys.argv[1:3]
text = open(src, encoding='utf-8').read()
pairs = sorted(set(re.findall(r'"([A-Za-z_][\w$.]*)@0x([0-9A-Fa-f]+)"', text)), key=lambda p: int(p[1], 16))
names = collections.defaultdict(list)
for name, addr in pairs:
    names[name].append(int(addr, 16))

KEEP_MULTI = {'AddIntcHandler', 'AddDmacHandler'}
kept, dropped = [], []
for name, addrs in names.items():
    if len(addrs) > 1 and name not in KEEP_MULTI:
        dropped.append((name, addrs))
        continue
    kept.extend((a, name) for a in addrs)
kept.sort()
with open(dst, 'w', encoding='utf-8', newline='\n') as f:
    f.write('# Generated by tools/analyzer_symbols.py from the SCE symbol database matches.\n')
    for addr, name in kept:
        f.write(f'{name} 0x{addr:08X}\n')
print('kept', len(kept), 'dropped names', len(dropped))
for name, addrs in dropped:
    print(' ', name, ' '.join(hex(a) for a in addrs[:8]))
# Where the libraries sit, to spot matches landing in the middle of game code.
buckets = collections.Counter(a >> 16 for a, _ in kept)
for b in sorted(buckets):
    print(f'  {b << 16:#010x}: {buckets[b]}')
